async function updateProducts() {
  console.log('⚡ Updating PostgreSQL products to Kickzone/Sneaker theme...');
  for (const prod of SNEAKER_PRODUCTS) {
    await pool.query(
      `UPDATE products
       SET name = $1,
           description = $2,
           current_price = $3,
           stock_quantity = $4,
           category = $5,
           image_url = $6,
           is_active = $7,
           updated_at = NOW()
       WHERE id = $8`,
      [
        prod.name,
        prod.description,
        prod.current_price,
        prod.stock_quantity,
        prod.category,
        prod.image_url,
        prod.is_active,
        prod.id,
      ]
    );
  }
  console.log('✅ Successfully updated all 21 products in PostgreSQL!');
  await pool.end();
}

updateProducts().catch((err) => {
  console.error('❌ Error updating products:', err);
  process.exit(1);
});
